#!/bin/sh
# Vendor deep-view into ds-bot so the package stays dependency-free.
#
#   sh scripts/vendor-deep-view.sh [path/to/deep-view-<version>.tgz]
#
# What it does, every run (idempotent, safe to replay after an upstream sync):
#   1. takes deep-view's npm tarball (argument, $DEEP_VIEW_TARBALL, or a download),
#      verifies its sha1 against the expected value for the version,
#   2. copies only LICENSE, package.json, src/core/, src/react/ into
#      ds-bot/vendor/deep-view/ (its client.js and cordis patch are not used),
#   3. rewrites the six external import sites to relative vendor paths,
#   4. drops `deep-view` from package.json dependencies (the zero-dependency gate
#      depends on this) and adds `vendor/` to files,
#   5. verifies: no bare `deep-view` specifier left anywhere in src/ or test/,
#      the vendored core loads, and the vendored tree itself imports nothing bare,
#   6. prints a key=value summary (files, KB, imports, dependencies) so a release
#      check can compare it against the package without counting by hand.
#
# Bump DEEP_VIEW_VERSION / DEEP_VIEW_SHA1 / DEEP_VIEW_GIT_HEAD together when moving
# to a new upstream version. Nothing here depends on the ds-bot version: it is read
# from package.json, so an upstream sync needs no edit to this script.
set -eu

VERSION="${DEEP_VIEW_VERSION:-0.1.2}"
SHA1="${DEEP_VIEW_SHA1:-6a0207ee0b6e9a8d96dc5f682ab66a6f6be2e124}"
GIT_HEAD="${DEEP_VIEW_GIT_HEAD:-dab178d026332bdb2016afe71e57eddf0747b850}"
TARBALL="${1:-${DEEP_VIEW_TARBALL:-}}"

PLUGIN="$(cd "$(dirname "$0")/.." && pwd)"
VENDOR="$PLUGIN/vendor/deep-view"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# 1. the tarball: given, cached, or downloaded from the mirror
if [ -z "$TARBALL" ] || [ ! -f "$TARBALL" ]; then
  TARBALL="$TMP/deep-view-$VERSION.tgz"
  echo "vendor-deep-view: downloading deep-view@$VERSION"
  curl -fsSL -o "$TARBALL" "https://registry.npmmirror.com/deep-view/-/deep-view-$VERSION.tgz"
fi
ACTUAL="$(sha1sum "$TARBALL" | cut -d' ' -f1)"
if [ "$ACTUAL" != "$SHA1" ]; then
  echo "vendor-deep-view: sha1 mismatch for $TARBALL" >&2
  echo "  expected $SHA1" >&2
  echo "  actual   $ACTUAL" >&2
  echo "  (if this is an intended version bump, update DEEP_VIEW_VERSION and DEEP_VIEW_SHA1)" >&2
  exit 1
fi

# 2. unpack and copy the parts ds-bot uses
tar xzf "$TARBALL" -C "$TMP"
SRC="$TMP/package"
GOT="$(node -p "require('$SRC/package.json').version")"
if [ "$GOT" != "$VERSION" ]; then
  echo "vendor-deep-view: tarball is $GOT, expected $VERSION" >&2
  exit 1
fi
rm -rf "$VENDOR"
mkdir -p "$VENDOR/src"
cp "$SRC/LICENSE" "$SRC/package.json" "$VENDOR/"
cp -R "$SRC/src/core" "$SRC/src/react" "$VENDOR/src/"
DSBOT_VERSION="$(node -p "require('$PLUGIN/package.json').version")"
cat > "$VENDOR/VENDORED.md" <<EOF
# Vendored deep-view

- vendored for: ds-bot \`$DSBOT_VERSION\`
- package: deep-view \`$VERSION\` — https://github.com/Fei2411/deep-view
- license: Apache-2.0 (see LICENSE in this directory)
- source: npm tarball sha1 \`$SHA1\`, gitHead \`$GIT_HEAD\`
- copied: LICENSE, package.json, src/core/, src/react/ — files unmodified;
  only ds-bot's own import specifiers are rewritten to point here.
- regenerated by \`scripts/vendor-deep-view.sh\`; do not edit by hand.
EOF

# 3. rewrite the external import sites (idempotent: matches the bare specifier only)
rewrite() {
  file="$1"; old="$2"; new="$3"
  [ -f "$file" ] || { echo "vendor-deep-view: missing $file" >&2; exit 1; }
  node -e '
    const fs = require("node:fs")
    const [file, oldSpec, newSpec] = process.argv.slice(1)
    const text = fs.readFileSync(file, "utf8")
    const from = "from \x27" + oldSpec + "\x27"
    const to = "from \x27" + newSpec + "\x27"
    if (text.includes(from)) fs.writeFileSync(file, text.split(from).join(to))
  ' "$file" "$old" "$new"
}
rewrite "$PLUGIN/src/host/parts.js"         deep-view/core  ../../vendor/deep-view/src/core/index.js
rewrite "$PLUGIN/src/host/tools.js"         deep-view/core  ../../vendor/deep-view/src/core/index.js
rewrite "$PLUGIN/src/host/channel.js"       deep-view/core  ../../vendor/deep-view/src/core/index.js
rewrite "$PLUGIN/src/client/widget-cell.js" deep-view/react ../../vendor/deep-view/src/react/index.js
rewrite "$PLUGIN/src/client/widget-cell.js" deep-view/core  ../../vendor/deep-view/src/core/index.js
rewrite "$PLUGIN/test/history.test.js"      deep-view/core  ../vendor/deep-view/src/core/index.js
rewrite "$PLUGIN/test/view-reply.test.js"   deep-view/core  ../vendor/deep-view/src/core/index.js

# 4. package.json: zero dependencies again, vendor/ in files
node -e '
  const fs = require("node:fs")
  const file = process.argv[1]
  const pkg = JSON.parse(fs.readFileSync(file, "utf8"))
  if (pkg.dependencies) {
    delete pkg.dependencies["deep-view"]
    if (Object.keys(pkg.dependencies).length === 0) delete pkg.dependencies
  }
  const files = Array.isArray(pkg.files) ? pkg.files : []
  if (!files.includes("vendor/")) files.push("vendor/")
  pkg.files = files
  fs.writeFileSync(file, JSON.stringify(pkg, null, 2) + "\n")
' "$PLUGIN/package.json"

# 5. verify
if grep -rn "from 'deep-view\|from \"deep-view\|require('deep-view" "$PLUGIN/src" "$PLUGIN/test" >/dev/null 2>&1; then
  echo "vendor-deep-view: a bare deep-view specifier is still there:" >&2
  grep -rn "from 'deep-view\|from \"deep-view\|require('deep-view" "$PLUGIN/src" "$PLUGIN/test" >&2
  exit 1
fi
if grep -rn "from 'deep-view\|from \"deep-view" "$VENDOR/src" >/dev/null 2>&1; then
  echo "vendor-deep-view: the vendored tree imports deep-view bare" >&2
  exit 1
fi
node --input-type=module -e "import('file://$VENDOR/src/core/index.js').then(m => { if (Object.keys(m).length === 0) process.exit(1) })"

# 6. summary: the numbers a release check compares against the built package
VFILES="$(find "$VENDOR" -type f | wc -l | tr -d ' ')"
VKB="$(du -sk "$VENDOR" | cut -f1)"
IMPORTS="$(grep -rn "from '.*vendor/deep-view/src/" "$PLUGIN/src" "$PLUGIN/test" | wc -l | tr -d ' ')"
DEPS="$(node -p "const p = require('$PLUGIN/package.json'); p.dependencies && Object.keys(p.dependencies).length ? Object.keys(p.dependencies).join(',') : 'none'")"
FILES_HAS="$(node -p "const p = require('$PLUGIN/package.json'); Array.isArray(p.files) && p.files.includes('vendor/') ? 'yes' : 'NO'")"

echo "--- vendor-deep-view summary ---"
echo "ds_bot_version=$DSBOT_VERSION"
echo "deep_view_version=$VERSION"
echo "deep_view_sha1=$SHA1"
echo "deep_view_git_head=$GIT_HEAD"
echo "vendor_files=$VFILES"
echo "vendor_size_kb=$VKB"
echo "imports_rewritten=$IMPORTS"
echo "dependencies=$DEPS"
echo "files_has_vendor=$FILES_HAS"

if ! grep -q "deep-view $VERSION" "$PLUGIN/NOTICE" 2>/dev/null; then
  echo "vendor-deep-view: WARNING: NOTICE has no 'deep-view $VERSION' section; add it (see the plan doc)" >&2
fi
echo "next: npm run build && node scripts/build-client.mjs --check && npm test"
