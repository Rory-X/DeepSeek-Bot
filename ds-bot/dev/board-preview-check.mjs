import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
const root = resolve(import.meta.dirname, '../..'), home = join(root, '.dsh-test-board-preview'), out = join(root, 'shots/board-preview')
const fixture = JSON.parse(await readFile(join(out, 'fixture.json'), 'utf8'))
const login = (await readFile(join(home, 'web.log'), 'utf8')).match(/http:\/\/127\.0\.0\.1:3121\/\?token=\S+/)?.[0]; assert.ok(login)
const { chromium } = await import(pathToFileURL(process.env.BOARD_PLAYWRIGHT).href)
const browser = await chromium.launch({ headless: true, env: { ...process.env, LD_LIBRARY_PATH: process.env.UI_VERIFY_LIBS } })
const checks = [], errors = []
const check = (name, value) => { assert.ok(value, name); checks.push(name); console.log('PASS ' + name) }
let page
try {
  for (const width of [1440, 390]) {
    page = await browser.newPage({ viewport: { width, height: 1000 }, isMobile: width < 900, hasTouch: width < 900, locale: 'zh-CN', colorScheme: width < 900 ? 'light' : 'dark' })
    page.on('pageerror', error => errors.push(error.message)); page.setDefaultTimeout(25000)
    await page.addLocatorHandler(page.getByRole('dialog').getByRole('button', { name: /^(Continue|继续)$/ }), locator => locator.click())
    await page.goto(login)
    const back = page.locator('[data-bt-nav-back]:visible').first(); if (width < 900 && await back.count()) await back.click()
    await page.locator('.bt-board-entry:visible').first().click()
    await page.locator('.bt-board-project').filter({ hasText: '交付物预览' }).click()
    await page.locator('.bt-board-card').filter({ hasText: new RegExp('#' + fixture.number + '\\b') }).click()
    const artifact = title => page.locator('.bt-board-deliverable').filter({ has: page.getByText(title, { exact: true }) })
    await artifact('设计与验收报告').getByRole('button', { name: '预览交付物', exact: true }).click()
    const column = page.locator('[data-rightbar-col]')
    await column.getByText('交付验收报告', { exact: true }).waitFor()
    check(`${width}: DSH renders Markdown beside the retained requirement`, await page.locator('.bt-board-drawer').count() === 1)
    if (width < 900) await page.waitForFunction(() => document.querySelector('.bt-board').inert, undefined, { timeout: 8000 })
    const geometry = await page.locator('.bt-board').evaluate(el => { const panel = document.querySelector('[data-rightbar-col]').getBoundingClientRect(); return { board: el.getBoundingClientRect().right, panel: panel.left, full: el.inert, scroll: el.querySelector('.bt-board-drawer-body').scrollWidth, width: el.querySelector('.bt-board-drawer-body').clientWidth } })
    check(`${width}: layout fits and fullscreen blocks covered board controls`, width < 900 ? geometry.full : geometry.board <= geometry.panel + 1 && geometry.scroll <= geometry.width + 1)
    await page.screenshot({ path: join(out, `${width}-markdown.png`) })
    // The native collapse action returns to the same card on mobile, and retains its tabs.
    const close = column.getByRole('button', { name: /收起|Collapse/ }).last()
    await close.click()
    await page.waitForFunction(() => !document.querySelector('.bt-board').inert)
    await artifact('界面截图').getByRole('button', { name: '预览交付物', exact: true }).click()
    await column.locator('img').first().waitFor()
    check(`${width}: DSH image renderer loaded the file`, await column.locator('img').first().evaluate(el => el.complete && el.naturalWidth > 0))
    await page.screenshot({ path: join(out, `${width}-image.png`) })
    await column.getByRole('button', { name: /收起|Collapse/ }).last().click()
    await page.waitForFunction(() => !document.querySelector('.bt-board').inert)
    await artifact('报告与截图合集').getByRole('button', { name: '预览交付物', exact: true }).click()
    await artifact('报告与截图合集').getByRole('button', { name: '验收报告', exact: true }).waitFor()
    check(`${width}: multiple references offer a choice`, await artifact('报告与截图合集').locator('.bt-board-preview-targets button').count() === 2)
    await artifact('报告与截图合集').getByRole('button', { name: '验收报告', exact: true }).click()
    await column.getByText('交付验收报告', { exact: true }).waitFor()
    await column.getByRole('button', { name: /收起|Collapse/ }).last().click()
    await page.waitForFunction(() => !document.querySelector('.bt-board').inert)
    await artifact('验证结果 JSON').getByRole('button', { name: '预览交付物', exact: true }).click()
    await column.getByText(/preview-bench/).first().waitFor()
    check(`${width}: code preview opens at the referenced line`, await column.innerText().then(text => text.includes('preview-bench')))
    await column.getByRole('button', { name: /收起|Collapse/ }).last().click()
    await page.waitForFunction(() => !document.querySelector('.bt-board').inert)
    await artifact('页面交付物').getByRole('button', { name: '预览交付物', exact: true }).click()
    await column.locator('iframe').first().contentFrame().getByRole('heading', { name: '交付页面预览' }).waitFor()
    check(`${width}: local HTML uses DSH's sandboxed viewer`, await column.locator('iframe').first().getAttribute('sandbox') !== null)
    await column.getByRole('button', { name: /收起|Collapse/ }).last().click()
    await page.waitForFunction(() => !document.querySelector('.bt-board').inert)
    await artifact('网页交付物').getByRole('button', { name: '预览交付物', exact: true }).click()
    await column.locator('iframe[src="http://127.0.0.1:8822/"]').contentFrame().getByRole('heading', { name: '交付页面预览' }).waitFor()
    check(`${width}: HTTP links open the native Browser tab`, await column.locator('iframe[src="http://127.0.0.1:8822/"]').count() === 1)
    await page.screenshot({ path: join(out, `${width}-web.png`) })
    await column.getByRole('button', { name: /收起|Collapse/ }).last().click()
    await page.waitForFunction(() => !document.querySelector('.bt-board').inert)
    await artifact('缺失文件').getByRole('button', { name: '预览交付物', exact: true }).click()
    await column.getByText(/找不到|不存在|not found/i).first().waitFor()
    check(`${width}: missing file has a native readable failure`, await column.innerText().then(text => /找不到|不存在|not found/i.test(text)))
    await column.getByRole('button', { name: /收起|Collapse/ }).last().click()
    await page.waitForFunction(() => !document.querySelector('.bt-board').inert)
    await artifact('提交记录说明').getByRole('button', { name: '预览交付物', exact: true }).click()
    check(`${width}: non-file reference stays available with explanation`, await artifact('提交记录说明').getByRole('alert').innerText().then(text => text.includes('没有可预览')))
    check(`${width}: closing previews preserves requirement and board`, await page.locator('.bt-board-drawer').count() === 1 && await page.locator('.bt-board').count() === 1)
    await page.close()
  }
  assert.deepEqual(errors, [])
  await writeFile(join(out, 'checks.json'), JSON.stringify({ checks, errors, realDshSidebar: true }, null, 2))
} catch (error) {
  if (page && !page.isClosed()) { await page.screenshot({ path: join(out, 'failure.png') }); console.log((await page.locator('.bt-board-preview-error').allTextContents()).join('\n')) }
  throw new Error(String(error.stack).replace(/token=[^\s)]+/g, 'token=REDACTED'))
} finally { await browser.close() }
