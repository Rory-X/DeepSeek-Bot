// Capture and exercise only the synthetic project-board bench.
// BOARD_PLAYWRIGHT points to an installed Playwright entry; UI_VERIFY_LIBS is optional.
import assert from 'node:assert/strict'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import { pathToFileURL } from 'node:url'

const root = resolve(import.meta.dirname, '../..')
const home = join(root, '.dsh-test-project-board')
const out = resolve(process.argv[2] ?? join(root, 'shots/project-board'))
const port = Number(process.argv[3] ?? 3107)
const { chromium } = await import(pathToFileURL(process.env.BOARD_PLAYWRIGHT).href)
const log = await readFile(join(home, 'web.log'), 'utf8')
const login = log.match(new RegExp('http://127\\.0\\.0\\.1:' + port + '/\\?token=[^\\s]+'))?.[0]
assert.ok(login, 'The isolated bench must be running')
await mkdir(out, { recursive: true })
const browser = await chromium.launch({ headless: true, env: { ...process.env, ...(process.env.UI_VERIFY_LIBS ? { LD_LIBRARY_PATH: process.env.UI_VERIFY_LIBS } : {}) } })
const results = []
const check = (name, passed) => { assert.ok(passed, name); results.push({ name, passed: true }); console.log('ok ' + name) }
try {
  const page = await browser.newPage({ viewport: { width: 1600, height: 1000 }, deviceScaleFactor: 1, locale: 'en-US', colorScheme: 'dark' })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addLocatorHandler(page.getByRole('dialog').getByRole('button', { name: /Continue|继续/ }), locator => locator.click())
  await page.goto(login)
  await page.locator('.bt-board-entry').first().waitFor({ timeout: 60000 })
  await page.locator('.bt-board-entry').first().click()
  await page.locator('.bt-board-project').filter({ hasText: 'Studio' }).waitFor({ timeout: 30000 })
  await page.locator('.bt-board-project').filter({ hasText: 'Studio' }).click()
  await page.locator('.bt-board-card').first().waitFor()
  await page.waitForTimeout(600)
  check('four board columns render', await page.locator('.bt-board-column').count() === 4)
  check('seven synthetic Studio requirements render', await page.locator('.bt-board-card').count() === 7)
  await page.screenshot({ path: join(out, '01-desktop-board.png') })
  await page.getByRole('button', { name: 'Add a focused requirement detail panel', exact: true }).click()
  await page.getByRole('dialog').waitFor()
  check('detail exposes five stages and a concrete decision', await page.locator('.bt-board-stages li').count() === 5 && await page.locator('.bt-board-decision').count() === 1)
  await page.screenshot({ path: join(out, '02-desktop-detail.png') })
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: 'New requirement', exact: true }).click()
  const draft = page.getByRole('dialog')
  await draft.getByLabel('Requirement title', { exact: true }).fill('Remember my board view')
  await draft.getByLabel('Requirement brief', { exact: true }).fill('Keep the selected project and search when I return to the board.')
  await draft.getByLabel('Acceptance criteria', { exact: true }).fill('A saved draft remains after page refresh. Switching projects does not move it.')
  await draft.getByRole('checkbox', { name: 'Nova', exact: true }).check()
  await page.screenshot({ path: join(out, '03-new-requirement.png') })
  await draft.getByRole('button', { name: 'Save draft', exact: true }).click()
  await page.getByRole('dialog').getByRole('heading', { name: 'Remember my board view', exact: true }).waitFor()
  check('draft creation saves and opens the new requirement', true)
  await page.getByRole('dialog').getByRole('button', { name: 'Edit draft', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Requirement title', { exact: true }).fill('Remember my project board view')
  await page.getByRole('dialog').getByRole('button', { name: 'Save draft', exact: true }).click()
  await page.getByRole('dialog').getByRole('heading', { name: 'Remember my project board view', exact: true }).waitFor()
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click()
  await page.reload()
  await page.locator('.bt-board-entry').first().click()
  await page.getByRole('button', { name: 'Remember my project board view', exact: true }).waitFor()
  check('draft edit survives a page reload', true)
  await page.locator('.bt-board-project').filter({ hasText: 'Companion' }).click()
  await page.getByRole('button', { name: 'Improve first-run guidance', exact: true }).waitFor()
  check('switching projects isolates their cards', await page.locator('.bt-board-card').count() === 1)
  await page.screenshot({ path: join(out, '04-second-project.png') })
  await page.locator('.bt-board-project').filter({ hasText: 'Studio' }).click()
  await page.getByLabel('Search requirements', { exact: true }).fill('conflicting')
  await page.getByRole('button', { name: 'Protect drafts from conflicting edits', exact: true }).waitFor()
  check('search filters requirement cards', await page.locator('.bt-board-card').count() === 1)
  await page.getByLabel('Search requirements', { exact: true }).fill('')
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true, locale: 'en-US', colorScheme: 'dark' })
  mobile.on('pageerror', error => errors.push(error.message))
  await mobile.addLocatorHandler(mobile.getByRole('dialog').getByRole('button', { name: /Continue|继续/ }), locator => locator.click())
  await mobile.goto(login)
  await mobile.locator('.bt-board-entry').first().waitFor({ timeout: 60000 })
  await mobile.locator('.bt-board-entry').first().click()
  await mobile.locator('.bt-board-project').filter({ hasText: 'Studio' }).waitFor()
  await mobile.locator('.bt-board-project').filter({ hasText: 'Studio' }).click()
  await mobile.locator('.bt-board-card').first().waitFor()
  await mobile.waitForTimeout(500)
  check('mobile board fits the screen and scrolls columns', await mobile.locator('.bt-board').evaluate(el => Math.abs(el.getBoundingClientRect().width - innerWidth) < 2))
  await mobile.screenshot({ path: join(out, '05-mobile-board.png') })
  await mobile.getByRole('button', { name: 'Add a focused requirement detail panel', exact: true }).click()
  await mobile.getByRole('dialog').waitFor()
  check('mobile details occupy the full width', await mobile.locator('.bt-board-drawer').evaluate(el => Math.abs(el.getBoundingClientRect().width - innerWidth) < 2))
  await mobile.screenshot({ path: join(out, '06-mobile-detail.png') })
  check('no uncaught client errors', errors.length === 0)
  const state = JSON.parse(await readFile(join(home, 'bot/state.json'), 'utf8'))
  check('draft has real persisted ownership and no execution', Object.values(state.board.cards).some(card => card.title === 'Remember my project board view' && card.status === 'backlog' && card.collaboratorIds.length === 1 && card.version === 2))
  await writeFile(join(out, 'checks.json'), JSON.stringify({ syntheticScenarios: true, results, errors }, null, 2))
} catch (error) {
  console.error(String(error).replace(/token=[^\s]+/g, 'token=[redacted]'))
  process.exitCode = 1
} finally {
  await browser.close()
}
