// Focused UI verification on the isolated mock bench; never use a real team.
import assert from 'node:assert/strict'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import { pathToFileURL } from 'node:url'
const root = resolve(import.meta.dirname, '../..')
const home = join(root, '.dsh-test-bot-folders')
const out = join(root, 'shots/bot-folders')
const port = 3120
const base = `http://127.0.0.1:${port}`
const { chromium } = await import(pathToFileURL(process.env.BOARD_PLAYWRIGHT).href)
const log = await readFile(join(home, 'web.log'), 'utf8')
const login = log.match(new RegExp(`http://127\\.0\\.0\\.1:${port}/\\?token=\\S+`))?.[0]
assert.ok(login, 'isolated bench is running')
const response = await fetch(login, { redirect: 'manual' })
const cookie = response.headers.getSetCookie().map(value => value.split(';')[0]).join('; ')
const api = async (endpoint, payload = {}) => {
  const result = await fetch(`${base}/api/bot`, { method: 'POST', headers: { cookie, 'Content-Type': 'application/json' }, body: JSON.stringify({ endpoint, payload }) }).then(r => r.json())
  assert.ok(result.ok, result.error?.message)
  return result.value
}
const check = (name, condition) => { assert.ok(condition, name); checks.push(name); console.log(`PASS ${name}`) }
const checks = [], errors = []
await mkdir(out, { recursive: true })
const names = ['Auth', 'Gmail', 'Slack', 'Drive', 'Calendar']
const initial = await api('state')
for (const folder of initial.botFolders) {
  await api('bot-folder-save', { ...folder, botIds: [] })
  await api('bot-folder-delete', { id: folder.id })
}
for (const name of [...names, 'Designer']) if (!initial.bots.some(bot => bot.name === name)) await api('create-bot', { name, role: name === 'Designer' ? 'Interface design' : `${name} connector` })
const browser = await chromium.launch({ headless: true, env: { ...process.env, LD_LIBRARY_PATH: process.env.UI_VERIFY_LIBS ?? '' } })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1, locale: 'en-US', colorScheme: 'dark' })
  page.on('pageerror', error => errors.push(error.message))
  await page.addLocatorHandler(page.getByRole('dialog').getByRole('button', { name: /Continue|继续/ }), locator => locator.click())
  await page.goto(login)
  await page.locator('.bt-list').waitFor({ timeout: 60000 })
  await page.getByRole('button', { name: 'New Bot folder', exact: true }).click()
  const dialog = page.locator('.bt-bot-folders-dialog')
  await dialog.getByLabel('Folder name', { exact: true }).fill('connector')
  for (const name of names) await dialog.getByRole('checkbox', { name: `${name} ${name} connector`, exact: true }).check()
  await page.screenshot({ path: join(out, '01-create-folder.png') })
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  const group = page.locator('.bt-bot-folder').filter({ has: page.getByRole('button', { name: 'connector', exact: true }) })
  const toggle = group.locator('.bt-bot-folder-toggle')
  await toggle.waitFor()
  check('heading is only connector, with no count', (await toggle.innerText()).trim() === 'connector')
  check('all five Bots are grouped once', await group.locator('[data-bot-id]').count() === 5 && await page.locator('.bt-list [data-bot-id]').count() === 7)
  check('ungrouped Designer remains visible', await page.locator('.bt-list').getByRole('button', { name: /^Designer,/ }).isVisible())
  await page.screenshot({ path: join(out, '02-desktop-expanded.png') })
  await toggle.click()
  check('click folds the group', await toggle.getAttribute('aria-expanded') === 'false' && await group.locator('[data-bot-id]').first().isHidden())
  await page.reload()
  await toggle.waitFor()
  await page.waitForFunction(() => document.querySelector('.bt-bot-folder-toggle')?.getAttribute('aria-expanded') === 'false')
  check('membership and folding survive reload', (await api('state')).botFolders[0].botIds.length === 5)
  await page.screenshot({ path: join(out, '03-desktop-collapsed.png') })
  // Search must still reach a Bot inside a folded section.
  await page.getByRole('button', { name: 'Search', exact: true }).first().click()
  const search = page.locator('.bt-palette input')
  await search.fill('Gmail')
  await page.keyboard.press('Enter')
  const gmailId = (await api('state')).bots.find(bot => bot.name === 'Gmail').id
  await page.waitForFunction(id => document.querySelector(`[data-bot-id="${id}"]`)?.getAttribute('aria-current') === 'page', gmailId)
  check('search opens a folded Bot without removing its membership', (await api('state')).botFolders[0].botIds.length === 5)
  await toggle.click()
  await toggle.focus()
  await page.keyboard.press('Enter')
  check('keyboard Enter folds the section', await toggle.getAttribute('aria-expanded') === 'false')
  await page.keyboard.press('Space')
  check('keyboard Space expands the section', await toggle.getAttribute('aria-expanded') === 'true')
  await group.getByRole('button', { name: 'Edit folder connector', exact: true }).click()
  await dialog.getByLabel('Folder name', { exact: true }).fill('integrations')
  await dialog.getByRole('checkbox', { name: 'Gmail Gmail connector', exact: true }).uncheck()
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  check('rename and unchecking a member persist', (await api('state')).botFolders[0].name === 'integrations' && (await api('state')).botFolders[0].botIds.length === 4)
  const gmail = (await api('state')).bots.find(bot => bot.name === 'Gmail')
  await page.locator(`[data-bot-id="${gmail.id}"]`).click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Move to folder…', exact: true }).click()
  await dialog.getByLabel('Bot folder', { exact: true }).selectOption({ label: 'integrations' })
  await dialog.getByLabel('Folder name', { exact: true }).fill('connector')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  check('Bot menu moves the Bot into an existing folder', (await api('state')).botFolders[0].botIds.length === 5)
  await page.getByRole('button', { name: 'New Bot folder', exact: true }).click()
  await dialog.getByLabel('Folder name', { exact: true }).fill('empty')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: 'Edit folder empty', exact: true }).click()
  await dialog.getByRole('button', { name: 'Delete empty folder', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  check('empty folder deletion preserves every Bot', (await api('state')).bots.length === 7 && (await api('state')).botFolders.length === 1)
  const phone = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true, locale: 'en-US', colorScheme: 'dark' })
  const mobile = await phone.newPage()
  mobile.on('pageerror', error => errors.push(error.message))
  await mobile.addLocatorHandler(mobile.getByRole('dialog').getByRole('button', { name: /Continue|继续/ }), locator => locator.click())
  await mobile.goto(login)
  await mobile.locator('[data-bt-nav="list"] .bt-bot-folder-toggle').waitFor({ timeout: 60000 })
  check('phone uses the same grouped list without duplicate rows', await mobile.locator('.bt-list').count() === 1 && await mobile.locator('.bt-bot-folder [data-bot-id]').count() === 5)
  await mobile.screenshot({ path: join(out, '04-mobile-expanded.png') })
  await mobile.getByRole('button', { name: 'connector', exact: true }).click()
  check('phone tap folds the group', await mobile.locator('.bt-bot-folder-rows').isHidden())
  await mobile.screenshot({ path: join(out, '05-mobile-collapsed.png') })
  await mobile.getByRole('button', { name: 'Edit folder connector', exact: true }).click()
  await mobile.locator('.bt-bot-folders-dialog').waitFor()
  check('phone dialog stays inside the viewport', await mobile.locator('.bt-bot-folders-dialog').evaluate(el => el.getBoundingClientRect().right <= innerWidth && el.getBoundingClientRect().left >= 0))
  await mobile.screenshot({ path: join(out, '06-mobile-manage.png') })
  check('no client errors', errors.length === 0)
  await writeFile(join(out, 'checks.json'), JSON.stringify({ checks, errors }, null, 2))
} finally { await browser.close() }
